const assert = require('node:assert/strict')
const path = require('node:path')

module.exports = async function checkCustomResolutions(browser, url, screenshots) {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    const dimensions = () => page.locator('#screenSize').textContent()
    const enter = async (id, value) => { await page.fill(id, value); await page.locator(id).press('Tab') }
    const selectPlayer = async () => {
        const id = await page.locator('#previewElement option').evaluateAll(options => options.find(o => o.text === 'Player Unit Frame').value)
        await page.selectOption('#previewElement', id)
        return page.locator(`[data-element=${JSON.stringify(id)}]`)
    }
    try {
        await page.goto(url, { waitUntil: 'networkidle' })
        await page.click('#demoUI')
        const input = await page.inputValue('#inputStr')
        await page.selectOption('#targetRes', 'custom')
        assert.equal(await page.inputValue('#targetWidth'), '3840')
        assert.equal(await page.inputValue('#targetHeight'), '2160')
        await enter('#targetWidth', '2560')
        await enter('#targetHeight', '1600')
        assert.equal(await page.inputValue('#manualScale'), '1.111')
        assert.equal(await page.textContent('#targetRatio'), '16:10')
        await page.click('#viewOriginal')
        assert.match(await dimensions(), /2560 × 1440/)
        await page.click('#viewScaled')
        assert.match(await dimensions(), /2560 × 1600/)
        await page.check('#showResolutions')
        const custom = await page.locator('[data-resolution="1600"] rect').evaluate(rect => ({
            x: Number(rect.getAttribute('x')), y: Number(rect.getAttribute('y')),
            width: Number(rect.getAttribute('width')), height: Number(rect.getAttribute('height')), stroke: rect.getAttribute('stroke-width')
        }))
        assert.deepEqual(custom, { x: 0, y: 0, width: 2560, height: 1600, stroke: '2' })
        assert.match(await page.textContent('#resolutionSizes'), /Custom · 2560 × 1600/)
        await page.click('#processBtn')
        const exported = await page.evaluate(() => ConfigCodec.decode(document.getElementById('outputStr').value))
        assert.equal(exported.configs[0].Position.X, -399.96)
        assert.equal(exported.configs[0].Position.Y, 366.63)
        assert.equal(await page.inputValue('#inputStr'), input)
        await page.selectOption('#baseRes', 'custom')
        await enter('#baseHeight', '1600')
        assert.equal(await page.inputValue('#manualScale'), '1.000')
        assert.equal(await page.isDisabled('#aspectRatio'), true)
        await page.click('#viewOriginal')
        assert.match(await dimensions(), /2560 × 1600/)
        await enter('#baseWidth', '1920')
        await enter('#baseHeight', '1200')
        assert.equal(await page.textContent('#baseRatio'), '16:10')
        assert.equal(await page.inputValue('#manualScale'), '1.333')
        await page.click('#undoEdit')
        assert.equal(await page.inputValue('#baseHeight'), '1600')
        assert.equal(await page.inputValue('#manualScale'), '1.000')
        await page.click('#undoEdit')
        assert.equal(await page.inputValue('#baseWidth'), '2560')
        await page.click('#redoEdit')
        assert.equal(await page.inputValue('#baseWidth'), '1920')
        await page.click('#undoEdit')
        await page.click('#viewScaled')
        await page.check('#editPositions')
        await page.uncheck('#smartGuides')
        const player = await selectPlayer()
        const before = Number(await page.inputValue('#positionX'))
        await player.scrollIntoViewIfNeeded()
        const box = await player.boundingBox(), svg = await page.locator('#previewSvg').boundingBox()
        const worldWidth = await page.locator('#previewSvg').evaluate(svg => svg.viewBox.baseVal.width)
        await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
        await page.mouse.down()
        await page.mouse.move(box.x + box.width / 2 + 20, box.y + box.height / 2 + 10, { steps: 4 })
        await page.mouse.up()
        assert.ok(Math.abs(Number(await page.inputValue('#positionX')) - before - 20 * worldWidth / svg.width) < .03)
        await page.click('#undoEdit')
        assert.equal(Number(await page.inputValue('#positionX')), before)
        await enter('#gridX', '32')
        await page.click('#snapSelected')
        const grid = await player.locator('rect').first().evaluate(rect => {
            const svg = rect.ownerSVGElement, box = svg.viewBox.baseVal
            return (Number(rect.getAttribute('x')) - box.x - box.width / 2) / 32
        })
        assert.ok(Math.abs(grid - Math.round(grid)) < .001)
        await page.click('#resetPosition')
        for (const bad of ['', '0', '-1', '1600.5', '32769']) {
            await page.fill('#targetHeight', bad)
            assert.equal(await page.isDisabled('#processBtn'), true)
            assert.equal(await page.inputValue('#outputStr'), '')
            assert.equal(await page.locator('[data-element]').count(), 0)
            assert.match(await page.textContent('#resolutionStatus'), /whole-pixel/)
            assert.equal(await page.locator('#previewSvg').evaluate(svg => {
                const box = svg.viewBox.baseVal
                return [box.x, box.y, box.width, box.height].every(Number.isFinite)
            }), true)
        }
        await enter('#targetHeight', '1600')
        assert.equal(await page.isDisabled('#processBtn'), false)
        await page.selectOption('#targetRes', '1080')
        assert.equal(await page.isDisabled('#targetWidth'), true)
        assert.equal(await page.isVisible('#targetCustom'), false)
        await page.selectOption('#targetRes', 'custom')
        assert.equal(await page.inputValue('#targetWidth'), '2560')
        assert.equal(await page.inputValue('#targetHeight'), '1600')
        await page.screenshot({ path: path.join(screenshots, 'custom-resolutions.png'), fullPage: true })
        await page.setViewportSize({ width: 390, height: 844 })
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
        await page.screenshot({ path: path.join(screenshots, 'custom-resolutions-mobile.png'), fullPage: true })
        await page.setViewportSize({ width: 1440, height: 1100 })
        await enter('#baseHeight', '32768')
        await enter('#targetHeight', '1')
        assert.ok(Number(await page.inputValue('#manualScale')) > 0)
        await page.click('#processBtn')
        assert.match(await page.textContent('#outputStatus'), /Ready/)
        await page.selectOption('#baseRes', '1080')
        await page.selectOption('#targetRes', '1440')
        await page.selectOption('#aspectRatio', '1.6')
        assert.equal(await page.isDisabled('#aspectRatio'), false)
        assert.match(await dimensions(), /2304 × 1440/)
        await page.click('#viewOriginal')
        assert.match(await dimensions(), /1728 × 1080/)
        await page.reload({ waitUntil: 'networkidle' })
        assert.equal(await page.inputValue('#aspectRatio'), '1.6')
        await page.selectOption('#baseRes', 'custom')
        assert.equal(await page.inputValue('#baseWidth'), '2304')
        await page.click('#demoCD')
        await page.selectOption('#targetRes', 'custom')
        await enter('#targetWidth', '3440')
        await enter('#targetHeight', '1440')
        await page.click('#processBtn')
        assert.match(await page.textContent('#outputStatus'), /Ready/)
        assert.match(await dimensions(), /3440 × 1440/)
        assert.equal(await page.textContent('#targetRatio'), '43:18')
        assert.deepEqual(errors, [])
        console.log('Custom sizes, aspect ratios, bounds, exports, history and editing checks passed.')
    } finally { await page.close() }
}
